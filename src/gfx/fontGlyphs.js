const ACCENTS = {
  acute: ['..#', '.#.'],
  tilde: ['.#.#', '#.#.'],
  diaeresis: ['....', '#.#.'],
};

const COMPOSED = {
  'á': ['a', 'acute'], 'é': ['e', 'acute'], 'í': ['ı', 'acute'], 'ó': ['o', 'acute'],
  'ú': ['u', 'acute'], 'ü': ['u', 'diaeresis'], 'ñ': ['n', 'tilde'],
  'Á': ['A', 'acute'], 'É': ['E', 'acute'], 'Í': ['I', 'acute'], 'Ó': ['O', 'acute'],
  'Ú': ['U', 'acute'], 'Ü': ['U', 'diaeresis'], 'Ñ': ['N', 'tilde'],
};

export const CELL_H = 11;
export const GLYPH_TOP = 2;
export const LINE_H = 13;

function padRows(rows) {
  const w = rows[0].length;
  const out = rows.slice();
  while (out.length < 9) out.push('.'.repeat(w));
  return out;
}

// Devuelve { width, rows[CELL_H] } con acentos compuestos en las filas 0-3.
function buildGlyph(ch) {
  if (G[ch]) {
    const rows = padRows(G[ch]);
    const w = rows[0].length;
    return { width: w, rows: ['.'.repeat(w), '.'.repeat(w), ...rows] };
  }
  const comp = COMPOSED[ch];
  if (!comp) return null;
  const base = padRows(G[comp[0]]);
  const acc = ACCENTS[comp[1]];
  const isUpper = comp[0] === comp[0].toUpperCase() && comp[0] !== 'ı';
  const w = Math.max(base[0].length, acc[0].length);
  const bx = Math.floor((w - base[0].length) / 2);
  const ax = Math.floor((w - acc[0].length) / 2) + (comp[1] === 'acute' && w > 3 ? 1 : 0);
  const grid = Array.from({ length: CELL_H }, () => Array(w).fill('.'));
  base.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') grid[y + GLYPH_TOP][x + bx] = '#';
  });
  const accTop = isUpper ? 0 : 1;
  acc.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const gx = x + ax;
      if (row[x] === '#' && gx >= 0 && gx < w) grid[y + accTop][gx] = '#';
    }
  });
  return { width: w, rows: grid.map((r) => r.join('')) };
}

export const GLYPHS = (() => {
  const chars = [...Object.keys(G), ...Object.keys(COMPOSED)].filter((c) => c !== 'ı');
  const out = {};
  for (const ch of chars) out[ch] = buildGlyph(ch);
  return out;
})();

export function charAdvance(ch) {
  const g = GLYPHS[ch] || GLYPHS['?'];
  return g.width + 1;
}

export function measure(text) {
  let w = 0;
  for (const ch of text) w += charAdvance(ch);
  return Math.max(0, w - 1);
}

// Parte el texto en líneas que caben en maxWidth, respetando saltos manuales.
export function wrap(text, maxWidth) {
  const lines = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const candidate = line ? `${line} ${word}` : word;
      if (measure(candidate) <= maxWidth || !line) {
        line = candidate;
      } else {
        lines.push(line);
        line = word;
      }
    }
    lines.push(line);
  }
  return lines;
}
